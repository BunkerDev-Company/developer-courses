/** 1990 → «1 990 ₽» (неразрывный пробел, без Intl — одинаково на сервере и в браузере). */
export function rub(n: number): string {
  return `${String(n).replace(/\B(?=(\d{3})+(?!\d))/g, ' ')} ₽`;
}
